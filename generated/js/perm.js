/* Permutation and finite-group toolkit.
 *
 * Convention: a permutation p of {0..n-1} is an array, and p[i] is where point i goes.
 * On a puzzle board, "point" = position, and applying p moves the token at position i to position p[i].
 * compose(a, b) means "do a, then b".
 * Works in the browser (window.Perm) and in Node (module.exports).
 */
(function (root) {
  'use strict';

  const identity = (n) => Array.from({ length: n }, (_, i) => i);
  const key = (p) => String.fromCharCode.apply(null, p);
  const compose = (a, b) => a.map((x) => b[x]); // first a, then b
  function inverse(p) { const q = new Array(p.length); p.forEach((x, i) => { q[x] = i; }); return q; }
  const isIdentity = (p) => p.every((x, i) => x === i);
  const equal = (a, b) => a.length === b.length && a.every((x, i) => x === b[i]);

  /* State action: state[i] = token sitting at position i. */
  function act(state, p) { const t = new Array(state.length); for (let i = 0; i < p.length; i++) t[p[i]] = state[i]; return t; }

  function cycles(p, keepFixed) {
    const seen = new Array(p.length).fill(false), out = [];
    for (let i = 0; i < p.length; i++) {
      if (seen[i]) continue;
      const c = []; let j = i;
      while (!seen[j]) { seen[j] = true; c.push(j); j = p[j]; }
      if (c.length > 1 || keepFixed) out.push(c);
    }
    return out;
  }
  const gcd = (a, b) => (b ? gcd(b, a % b) : a);
  const lcm = (a, b) => (a / gcd(a, b)) * b;
  const order = (p) => cycles(p).reduce((m, c) => lcm(m, c.length), 1);
  /* +1 for even, -1 for odd. A k-cycle is a product of k-1 transpositions. */
  const sign = (p) => (cycles(p).reduce((s, c) => s + c.length - 1, 0) % 2 ? -1 : 1);

  /* Cycle notation, 1-indexed for humans: "(1 2 3)(4 5)". */
  function toCycles(p, labels) {
    const lab = labels || ((i) => String(i + 1));
    const cs = cycles(p);
    if (!cs.length) return 'e';
    return cs.map((c) => '(' + c.map(lab).join(' ') + ')').join('');
  }
  function parseCycles(str, n) {
    const s = str.trim();
    if (s === '' || s === 'e' || s === '()') return identity(n || 0);
    if (!/^(\s*\(\s*\d+(\s*[ ,]\s*\d+)*\s*\)\s*)+$/.test(s)) throw new Error('Could not read "' + str + '". Write cycles like (1 2 3)(4 5).');
    const cs = [...s.matchAll(/\(([^)]*)\)/g)].map((m) => m[1].split(/[\s,]+/).filter(Boolean).map((x) => parseInt(x, 10) - 1));
    let m = n || 0;
    cs.forEach((c) => c.forEach((x) => { if (x < 0) throw new Error('Points are numbered from 1.'); m = Math.max(m, x + 1); }));
    let p = identity(m);
    for (let k = cs.length - 1; k >= 0; k--) { // rightmost cycle acts first (standard convention)
      const c = cs[k];
      if (new Set(c).size !== c.length) throw new Error('A cycle repeats a point: (' + c.map((x) => x + 1).join(' ') + ')');
      const q = identity(m);
      c.forEach((x, i) => { q[x] = c[(i + 1) % c.length]; });
      p = compose(p, q);
    }
    return p;
  }
  /* Same as parseCycles but for 0-indexed cycle arrays, e.g. [[0,1,2],[3,4]]. */
  function fromCycles(cs, n) {
    const p = identity(n);
    cs.forEach((c) => c.forEach((x, i) => { p[x] = c[(i + 1) % c.length]; }));
    return p;
  }
  const pad = (p, n) => (p.length >= n ? p : p.concat(identity(n).slice(p.length)));

  /* Breadth-first search of the orbit of `start` under the moves `gens`.
   * `apply(x, g)` returns the new point. Returns nodes in BFS order with parent links,
   * or { overflow: true } if more than `limit` points are found. */
  function bfs(start, gens, apply, limit) {
    limit = limit || 200000;
    const index = new Map(), nodes = [start], parent = [-1], via = [-1], dist = [0];
    index.set(key(start), 0);
    for (let h = 0; h < nodes.length; h++) {
      const x = nodes[h];
      for (let g = 0; g < gens.length; g++) {
        const y = apply(x, gens[g]), k = key(y);
        if (index.has(k)) continue;
        if (nodes.length >= limit) return { overflow: true, size: nodes.length };
        index.set(k, nodes.length); nodes.push(y); parent.push(h); via.push(g); dist.push(dist[h] + 1);
      }
    }
    return { nodes, index, parent, via, dist, size: nodes.length };
  }
  /* Word (list of generator indices) from the BFS root to node i. */
  function wordTo(res, i) { const w = []; while (res.parent[i] >= 0) { w.push(res.via[i]); i = res.parent[i]; } return w.reverse(); }

  /* The group generated by gens: every element as a permutation. */
  function generate(gens, limit) {
    const n = gens.reduce((m, g) => Math.max(m, g.length), 0);
    const gs = gens.map((g) => pad(g, n));
    const r = bfs(identity(n), gs, compose, limit);
    if (!r.overflow) r.n = n;
    return r;
  }

  function divisors(N) { const d = []; for (let i = 1; i <= N; i++) if (N % i === 0) d.push(i); return d; }
  function factor(N) { const f = {}; for (let p = 2; p * p <= N; p++) while (N % p === 0) { f[p] = (f[p] || 0) + 1; N /= p; } if (N > 1) f[N] = (f[N] || 0) + 1; return f; }
  function partitions(k, max) { // integer partitions of k, parts <= max, non-increasing
    max = max === undefined ? k : max;
    if (k === 0) return [[]];
    const out = [];
    for (let a = Math.min(k, max); a >= 1; a--) partitions(k - a, a).forEach((r) => out.push([a].concat(r)));
    return out;
  }
  const fact = (k) => (k <= 1 ? 1 : k * fact(k - 1));
  const SUB = '₀₁₂₃₄₅₆₇₈₉';
  const sub = (k) => String(k).split('').map((d) => SUB[+d]).join('');

  /* Analyse a generated group: order statistics, centre, and a best-effort name. */
  function analyse(gens) {
    const G = generate(gens, 60000);
    if (G.overflow) return { overflow: true };
    const els = G.nodes, N = els.length, n = G.n;
    const gs = gens.map((g) => pad(g, n));
    const ords = els.map(order);
    const orderCount = {};
    ords.forEach((o) => { orderCount[o] = (orderCount[o] || 0) + 1; });
    const commutes = (a, b) => equal(compose(a, b), compose(b, a));
    let abelian = true;
    for (let i = 0; i < gs.length && abelian; i++) for (let j = i + 1; j < gs.length; j++) if (!commutes(gs[i], gs[j])) { abelian = false; break; }
    const centre = els.filter((x) => gs.every((g) => commutes(x, g))).length;
    const even = els.filter((x) => sign(x) === 1).length;
    const moved = new Set(); gs.forEach((g) => g.forEach((x, i) => { if (x !== i) moved.add(i); }));
    const k = moved.size;
    const names = [];
    const maxOrd = Math.max.apply(null, ords);
    if (N === 1) names.push('the trivial group');
    else if (abelian) {
      if (maxOrd === N) names.push('C' + sub(N) + ' (cyclic)');
      else {
        // Match the counts #{x : x^d = e} against every abelian group of order N.
        const f = factor(N), primes = Object.keys(f).map(Number);
        const countDiv = (d) => ords.filter((o) => d % o === 0).length;
        let options = [[]];
        primes.forEach((p) => {
          const next = [];
          options.forEach((o) => partitions(f[p]).forEach((part) => next.push(o.concat(part.map((a) => Math.pow(p, a))))));
          options = next;
        });
        const hit = options.find((fs) => divisors(N).every((d) => fs.reduce((m, q) => m * gcd(d, q), 1) === countDiv(d)));
        if (hit) {
          const fs = hit.slice().sort((a, b) => a - b);
          names.push(fs.map((q) => 'C' + sub(q)).join(' × ') + (N === 4 ? ' (the Klein four-group)' : ''));
        }
      }
    } else {
      if (N === fact(k)) names.push('S' + sub(k) + ' (all permutations of the ' + k + ' moved points)');
      if (k >= 4 && N === fact(k) / 2 && even === N) names.push('A' + sub(k) + ' (all even permutations of the ' + k + ' moved points)');
      if (N % 2 === 0 && N >= 6) {
        const m = N / 2;
        const r = els.find((x, i) => ords[i] === m);
        if (r) {
          const R = generate([r]).nodes.map(key), inR = new Set(R);
          if (els.every((x, i) => inR.has(key(x)) || ords[i] === 2)) names.push('D' + sub(m) + ' (symmetries of a regular ' + m + '-gon)');
        }
      }
      if (N === 8 && orderCount[2] === 1) names.push('Q₈ (the quaternion group)');
      if (!names.length) {
        // Same element-order profile as S_m or A_m (m ≤ 6)? For these small orders that pins the group down.
        for (let m = 3; m <= 6 && !names.length; m++) {
          [[fact(m), 'S'], [fact(m) / 2, 'A']].forEach(([size, kind]) => {
            if (names.length || size !== N || (kind === 'A' && m < 4)) return;
            const ref = profile(m, kind === 'A');
            if (Object.keys(ref).length === Object.keys(orderCount).length && Object.keys(ref).every((o) => ref[o] === orderCount[o]))
              names.push('≅ ' + kind + sub(m) + ' (same element orders as ' + kind + sub(m) + ', acting on ' + k + ' points)');
          });
        }
      }
    }
    return { N, n, k, ords, orderCount, abelian, centre, even, names, elements: els, bfs: G, gens: gs };
  }

  const profiles = {};
  function profile(m, alt) {
    const id = m + (alt ? 'A' : 'S');
    if (profiles[id]) return profiles[id];
    const gens = alt ? [fromCycles([[0, 1, 2]], m), fromCycles([Array.from({ length: m - (m % 2 ? 0 : 1) }, (_, i) => i + (m % 2 ? 0 : 1))], m)] : [fromCycles([[0, 1]], m), fromCycles([Array.from({ length: m }, (_, i) => i)], m)];
    const c = {};
    generate(gens).nodes.forEach((x) => { const o = order(x); c[o] = (c[o] || 0) + 1; });
    return (profiles[id] = c);
  }
  const api = { identity, key, compose, inverse, isIdentity, equal, act, cycles, order, sign, gcd, lcm, toCycles, parseCycles, fromCycles, pad, bfs, wordTo, generate, analyse, sub, fact };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.Perm = api;
})(typeof window !== 'undefined' ? window : this);
